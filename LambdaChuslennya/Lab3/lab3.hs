module Lab3 where

-- myRemoveAt видаляє N-ний елемент зі списку, де N інтерпретується як 1-базована позиція.
--
-- Логіка роботи:
-- 1) Якщо n <= 0, повертаємо початковий список без змін (некоректна позиція).
-- 2) Розбиваємо список на дві частини через splitAt (n - 1):
--    left  - елементи до позиції n,
--    right - елемент на позиції n та все, що після нього.
-- 3) Видаляємо перший елемент right через drop 1 та з'єднуємо назад.
--
-- Поведінка на межах:
-- - Якщо n більше за довжину списку, right буде порожнім, тому список не зміниться.
-- - Для порожнього списку результат теж порожній.
--
-- Приклад: myRemoveAt 2 "abcd" == "acd"
myRemoveAt :: Int -> [a] -> [a]
myRemoveAt n xs
  | n <= 0 = xs
  | otherwise = left ++ drop 1 right
  where
    (left, right) = splitAt (n - 1) xs

-- myInsertAt вставляє елемент x у список xs на 1-базовану позицію n.
--
-- Трактування позиції:
-- - n = 1: вставка на початок списку.
-- - n = 2: вставка між 1-м і 2-м елементами.
-- - n > довжина списку: елемент додається в кінець.
--
-- Логіка роботи:
-- 1) Якщо n <= 1, виконуємо prepend: x : xs.
-- 2) Інакше використовуємо splitAt (n - 1), щоб отримати частину до позиції
--    та решту списку, після чого вставляємо x між цими частинами.
--
-- Приклад: myInsertAt 'X' "abcd" 2 == "aXbcd"
myInsertAt :: a -> [a] -> Int -> [a]
myInsertAt x xs n
  | n <= 1 = x : xs
  | otherwise = left ++ [x] ++ right
  where
    (left, right) = splitAt (n - 1) xs

-- myDuplicate дублює кожен елемент списку, зберігаючи початковий порядок.
--
-- Реалізація через concatMap:
-- - для кожного елемента x будуємо список [x, x],
-- - потім "склеюємо" всі такі пари в один список.
--
-- Приклад: myDuplicate [1,2,3] == [1,1,2,2,3,3]
myDuplicate :: [a] -> [a]
myDuplicate = concatMap (\x -> [x, x])

-- myCompress видаляє лише послідовні дублікати.
--
-- Однакові елементи, розділені іншими значеннями,
-- не видаляються, бо вони не є послідовними.
--
-- Підхід:
-- 1) Перший елемент залишаємо завжди.
-- 2) Далі рекурсивна допоміжна функція go порівнює поточний елемент
--    з попереднім збереженим:
--    - якщо однакові -> пропускаємо поточний,
--    - якщо різні -> додаємо поточний у результат і оновлюємо "попередній".
--
-- Приклад: myCompress "aaaabccaadeeee" == "abcade"
myCompress :: Eq a => [a] -> [a]
myCompress [] = []
myCompress (x:xs) = x : go x xs
  where
    go _ [] = []
    go prev (y:ys)
      | prev == y = go prev ys
      | otherwise = y : go y ys

-- myMap реалізує поведінку стандартної map через foldr.
--
-- Ідея foldr:
-- - проходимо список справа наліво,
-- - до акумулятора acc додаємо f x на початок,
-- - стартовий акумулятор - порожній список [].
--
-- Така реалізація повністю еквівалентна map за результатом.
--
-- Приклад: myMap (*2) [1,2,3,4] == [2,4,6,8]
myMap :: (a -> b) -> [a] -> [b]
myMap f = foldr (\x acc -> f x : acc) []
